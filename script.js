/**
 * Food Express — script.js (root)
 *
 * Compatibility + bootstrap shim kept at the repository root because the
 * project's documented file contract (see README.md) names `script.js` as the
 * root entry point. All real logic lives in the namespaced modules:
 *
 *   shared/*.js        seed data + pricing engine (single source of truth)
 *   js/config.js       runtime configuration (API_URL, USE_BACKEND, limits)
 *   js/utils.js        DOM/format/validation helpers          → FX.u
 *   js/media.js        locally generated product imagery      → FX.media
 *   js/api.js          fetch wrapper + token handling         → FX.api
 *   js/backend-integration.js  backend adapters               → FX.backend
 *   js/store.js        state, cart, auth, orders, admin       → FX.store
 *   js/ui.js           reusable UI components                 → FX.ui
 *   js/components/*.js header, footer, nav, drawers, listing
 *   js/app.js          boot sequence, guards, page lifecycle  → FX.app
 *   js/pages/*.js      one controller per page
 *
 * This file adds nothing to the boot order — pages are generated by
 * `node tools/build-pages.js`, which already includes every module above in
 * dependency order. It exists so that legacy bookmarks, the documented
 * contract and any external snippet that expects `window.FoodExpress` or a
 * global `API_URL` keep working.
 */
(function (global) {
  'use strict';

  var FX = global.FX || {};

  /** Legacy global alias used by older documentation and snippets. */
  global.FoodExpress = FX;

  /**
   * Legacy configuration globals. These mirror FX.config so that anything
   * reading `window.API_URL` / `window.USE_BACKEND` sees the same values the
   * app itself uses — there is deliberately no second source of truth.
   */
  if (FX.config) {
    global.API_URL = FX.config.API_URL;
    global.USE_BACKEND = FX.config.USE_BACKEND;
  }

  /**
   * Convenience wrapper: run a callback once the store has booted.
   * Equivalent to FX.app.onReady(fn) and safe to call before or after boot.
   */
  FX.ready = function ready(callback) {
    if (typeof callback !== 'function') return Promise.resolve(FX.store ? FX.store.state : null);
    if (FX.app && typeof FX.app.onReady === 'function') return FX.app.onReady(callback);
    return Promise.resolve(callback(FX.store ? FX.store.state : null));
  };

  /** Small diagnostics helper — handy in the browser console, harmless in prod. */
  FX.debug = function debug() {
    var store = FX.store;
    if (!store) return { error: 'FX.store is not loaded — check the script order in the page.' };
    return {
      mode: store.mode(),
      page: document.body.dataset.page || null,
      location: store.location.current(),
      serviceable: store.location.isServiceable(),
      cart: { type: store.cart.type, lines: store.cart.items.length, count: store.cart.count(), totals: store.cart.totals() },
      wishlist: store.wishlist.count(),
      user: store.auth.user() ? { name: store.auth.user().name, role: store.auth.user().role } : null,
      orders: store.orders.list().length,
      points: store.rewards.points(),
      products: store.catalog.products().length,
      restaurants: store.catalog.restaurants().length,
      settings: {
        freeDeliveryThreshold: store.settings.get().freeDeliveryThreshold,
        deliveryFee: store.settings.get().deliveryFee,
      },
    };
  };

  global.FX = FX;
})(typeof globalThis !== 'undefined' ? globalThis : this);
